"""Local future-energy allocation for a multiple-shooting closure.

The sidecar does not predict another future field.  It predicts one spatial
log-energy correction from the closure's causal history context, the energy
already generated by the rollout, and the energy observed in the input.  The
correction scales only zero-temporal-mean u/v fluctuations, so it cannot alter
the predicted temporal mean or pressure channel.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass

import torch
from torch import nn
import torch.nn.functional as F

from .multiple_shooting_closure import MultipleShootingClosure


@dataclass(frozen=True)
class MSLocalEnergyConfig:
    hidden_channels: int = 32
    groups: int = 8
    log_limit: float = 1.0
    energy_reference: float = 0.01
    epsilon: float = 1.0e-8

    def validate(self, context_channels: int) -> None:
        if self.hidden_channels <= 0 or context_channels <= 0:
            raise ValueError("energy-controller widths must be positive")
        if self.groups <= 0 or self.hidden_channels % self.groups:
            raise ValueError("groups must divide hidden channels")
        if self.log_limit <= 0 or self.energy_reference <= 0 or self.epsilon <= 0:
            raise ValueError("energy-controller scales must be positive")


class MSLocalEnergyController(nn.Module):
    """Predict one bounded local log-TKE correction shared by u/v and time."""

    def __init__(self, context_channels: int,
                 config: MSLocalEnergyConfig = MSLocalEnergyConfig()) -> None:
        super().__init__()
        config.validate(context_channels)
        self.context_channels = int(context_channels)
        self.config = config
        self.body = nn.Sequential(
            nn.Conv2d(context_channels + 2, config.hidden_channels, 1),
            nn.GroupNorm(config.groups, config.hidden_channels),
            nn.SiLU(),
            nn.Conv2d(
                config.hidden_channels, config.hidden_channels, 3,
                padding=1, groups=config.hidden_channels),
            nn.SiLU(),
            nn.Conv2d(config.hidden_channels, 1, 1),
        )
        nn.init.zeros_(self.body[-1].weight)
        nn.init.zeros_(self.body[-1].bias)

    def architecture_config(self) -> dict[str, object]:
        return {
            "architecture": "msclosure_local_energy_controller",
            "context_channels": self.context_channels,
            **asdict(self.config),
        }

    @staticmethod
    def physical_tke(physical_uv: torch.Tensor) -> torch.Tensor:
        if physical_uv.ndim != 5 or physical_uv.shape[-1] != 2:
            raise ValueError("physical velocity must have shape [B,T,H,W,2]")
        fluctuation = physical_uv - physical_uv.mean(dim=1, keepdim=True)
        return 0.5 * fluctuation.square().mean(dim=1).sum(dim=-1)

    def forward(self, context: torch.Tensor, future_tke: torch.Tensor,
                history_tke: torch.Tensor) -> torch.Tensor:
        if context.ndim != 4 or context.shape[1] != self.context_channels:
            raise ValueError("energy context must have shape [B,C,H,W]")
        if future_tke.shape != history_tke.shape or future_tke.ndim != 3:
            raise ValueError("energy maps must have matching [B,H,W] shapes")
        if context.shape[0] != future_tke.shape[0]:
            raise ValueError("energy context batch changed")
        if context.shape[-2:] != future_tke.shape[-2:]:
            context = F.interpolate(
                context, size=future_tke.shape[-2:], mode="bilinear",
                align_corners=False)
        scale = self.config.energy_reference
        conditioning = torch.stack((
            torch.log1p(future_tke.clamp_min(0.0) / scale),
            torch.log1p(history_tke.clamp_min(0.0) / scale),
        ), dim=1)
        raw = self.body(torch.cat((context, conditioning), dim=1))
        return self.config.log_limit * torch.tanh(raw)


class FrozenMSClosureLocalEnergy(nn.Module):
    """Attach a trainable local-energy controller to a frozen MS closure."""

    def __init__(self, base: MultipleShootingClosure,
                 controller: MSLocalEnergyController | None = None) -> None:
        super().__init__()
        self.base = base
        self.controller = controller or MSLocalEnergyController(
            base.config.context_channels)
        for parameter in self.base.parameters():
            parameter.requires_grad_(False)
        self.base.eval()

    def architecture_config(self) -> dict[str, object]:
        return {
            "architecture": "frozen_msclosure_local_energy",
            "base": self.base.architecture_config(),
            "controller": self.controller.architecture_config(),
            "shared_across_horizon": True,
            "shared_across_velocity_components": True,
            "preserves_temporal_mean": True,
        }

    def train(self, mode: bool = True):
        super().train(mode)
        self.base.eval()
        self.controller.train(mode)
        return self

    def _history_physical_uv(self, history: torch.Tensor) -> torch.Tensor:
        mean = self.base.mean_input[:2].to(history)
        std = self.base.std_input[:2].to(history)
        return history[..., :2] * std + mean

    def forward_with_aux(self, history: torch.Tensor) -> dict[str, torch.Tensor]:
        # no_grad, rather than inference_mode, leaves ordinary detached tensors
        # that can safely condition a trainable controller.
        with torch.no_grad():
            components = self.base.forward_components(history)
        physical_uv = components["physical_uv"].detach()
        context = components["context"].detach()
        future_tke = self.controller.physical_tke(physical_uv)
        history_tke = self.controller.physical_tke(
            self._history_physical_uv(history))
        delta_logk = self.controller(
            context, future_tke.detach(), history_tke.detach())
        free_mask = components["free_mask"].permute(0, 3, 1, 2)
        delta_logk = torch.where(
            free_mask, delta_logk, torch.zeros_like(delta_logk))

        temporal_mean = physical_uv.mean(dim=1, keepdim=True)
        fluctuation = physical_uv - temporal_mean
        relative_amplitude = torch.expm1(
            0.5 * delta_logk.permute(0, 2, 3, 1)).unsqueeze(1)
        correction = fluctuation * relative_amplitude
        # This centering makes the invariant explicit even under finite
        # precision; it is exactly zero when the zero-initialized head is zero.
        correction = correction - correction.mean(dim=1, keepdim=True)
        corrected_physical_uv = physical_uv + correction

        target_mean = self.base.mean_target[:2].to(history)
        target_std = self.base.std_target[:2].to(history)
        normalized_uv = (corrected_physical_uv - target_mean) / target_std
        prediction = torch.cat((
            normalized_uv, components["prediction"][..., 2:].detach()), dim=-1)
        return {
            "prediction": prediction,
            "delta_logk": delta_logk,
            "future_tke": future_tke,
            "history_tke": history_tke,
            "base_prediction": components["prediction"].detach(),
            "corrected_physical_uv": corrected_physical_uv,
            "base_physical_uv": physical_uv,
            "free_mask": components["free_mask"],
        }

    def forward(self, history: torch.Tensor) -> torch.Tensor:
        return self.forward_with_aux(history)["prediction"]
